    @Test
    void updateTemplateRefreshesPresetMappingsAndRemovesStaleRows() throws Exception {
        String createPayload = """
                {
                  "name": "Preset Rename Source",
                  "request": {
                    "baseEntity": "DOCUMENT_PARENT",
                    "columns": ["DOCUMENT_NUMBER"],
                    "filters": [
                      {
                        "key": "CREATED_AT",
                        "op": "BETWEEN",
                        "mode": "USER_INPUT",
                        "logicalType": "DATE",
                        "dataType": "DATE",
                        "presetCodes": ["THIS_WEEK", "THIS_MONTH"]
                      }
                    ]
                  }
                }
                """;

        long templateId = objectMapper.readTree(mockMvc.perform(post("/api/reports/templates")
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("X-USER-ID", "creator1")
                        .content(createPayload))
                .andExpect(status().isCreated())
                .andReturn().getResponse().getContentAsString()).get("id").asLong();

        String updatePayload = """
                {
                  "name": "Preset Rename Target",
                  "request": {
                    "baseEntity": "DOCUMENT_PARENT",
                    "columns": ["DOCUMENT_NUMBER"],
                    "filters": [
                      {
                        "key": "CREATED_AT",
                        "op": "BETWEEN",
                        "mode": "USER_INPUT",
                        "logicalType": "DATE",
                        "dataType": "DATE",
                        "presetCodes": ["PREVIOUS_WEEK"]
                      }
                    ]
                  }
                }
                """;

        mockMvc.perform(put("/api/reports/templates/{id}", templateId)
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("X-USER-ID", "editor1")
                        .content(updatePayload))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.name").value("Preset Rename Target"))
                .andExpect(jsonPath("$.request.filters[0].presetCodes[0]").value("PREVIOUS_WEEK"));

        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM REPORT_FILTER_PRESET_MAP WHERE REPORT_CODE = ?",
                Integer.class,
                "Preset Rename Source"
        )).isEqualTo(0);
        assertThat(jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM REPORT_FILTER_PRESET_MAP WHERE REPORT_CODE = ? AND PRESET_CODE = ?",
                Integer.class,
                "Preset Rename Target",
                "PREVIOUS_WEEK"
        )).isEqualTo(1);
    }

