    private void assertSingleDocument(MvcResult result, String expectedDocumentNumber) throws Exception {
        JsonNode json = objectMapper.readTree(result.getResponse().getContentAsString());
        assertThat(json.get("rows").isArray()).isTrue();
        assertThat(json.get("rows").size()).isEqualTo(1);
        Map<String, String> displayToActual = new LinkedHashMap<>();
        for (JsonNode columnNode : json.get("columns")) {
            String actualName = columnNode.asText();
            String displayName = actualName.contains(".") ? actualName.substring(actualName.indexOf('.') + 1) : actualName;
            displayToActual.put(displayName, actualName);
        }
        assertThat(json.get("rows").get(0).get(displayToActual.get("DOCUMENT_NUMBER")).asText()).isEqualTo(expectedDocumentNumber);
    }
