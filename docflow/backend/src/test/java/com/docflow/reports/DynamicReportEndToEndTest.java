    @Test
    void endToEndReportFlow() throws Exception {
        Mockito.reset(reportBuilder);
        Mockito.doAnswer(invocation -> {
            DynamicReportBuilder.BuiltReport built = (DynamicReportBuilder.BuiltReport) invocation.callRealMethod();
            System.out.println("Generated SQL: " + built.sql());
            return built;
        }).when(reportBuilder).build(any(DynamicReportRequest.class));

        mockMvc.perform(get("/api/reports/admin/scope").param("baseEntity", "LOAN_DATA"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.entities[0].name").value("DOCUMENT_PARENT"))
                .andExpect(jsonPath("$.baseColumns").isArray())
                .andExpect(jsonPath("$.metadataKeys").isArray());

        String templatePayload = """
                {
                  "name": "Loans over 15L",
                  "request": {
                    "baseEntity": "LOAN_DATA",
                    "columns": ["DOCUMENT_PARENT.DOCUMENT_NUMBER", "LOAN_AMOUNT", "COMPLETION_DATE", "meta:state"],
                    "filters": [
                      {"key": "LOAN_AMOUNT", "op": ">", "value": "1500000"},
                      {"key": "meta:state", "op": "=", "value": "Tamil Nadu"}
                    ]
                  }
                }
                """;

        MvcResult saveResult = mockMvc.perform(post("/api/reports/templates")
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("X-USER-ID", "tester")
                        .content(templatePayload))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.id").isNumber())
                .andExpect(jsonPath("$.name").value("Loans over 15L"))
                .andExpect(jsonPath("$.createdBy").value("tester"))
                .andReturn();

        long templateId = objectMapper.readTree(saveResult.getResponse().getContentAsString()).get("id").asLong();
        assertThat(templateId).isPositive();
        Map<String, Object> persistedTemplate = jdbcTemplate.queryForMap(
                "SELECT created_by, updated_by, updated_at FROM report_templates WHERE id = ?",
                templateId
        );
        assertThat(persistedTemplate.get("created_by")).isEqualTo("tester");
        assertThat(persistedTemplate.get("updated_by")).isNull();
        assertThat(persistedTemplate.get("updated_at")).isNull();

        mockMvc.perform(get("/api/reports/templates"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.templates[0].id").value(templateId))
                .andExpect(jsonPath("$.templates[0].name").value("Loans over 15L"))
                .andExpect(jsonPath("$.templates[0].request.baseEntity").value("LOAN_DATA"));

        runCaseLoansOver15L();
        runCaseMetadataState();
        runCaseKycPending();
        runCaseMetadataAge();
        runCaseCompletionDateBetween();
        runCaseLoanAmountRange();
        runCaseLoanAmountAndMetadata();
        runCaseCreatedAt();
    }

